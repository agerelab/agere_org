/**
 * Agere DS token pipeline — Style Dictionary v5 (DTCG format).
 *
 *   tokens/**.json  ──►  src/styles/tokens.css          (web: CSS custom properties, light + dark)
 *                   ──►  src/tokens/generated/*.ts       (web: typed JS objects for Tailwind / runtime)
 *                   ──►  build/tokens/tokens.{light,dark}.json   (Figma Tokens Studio / docs)
 *                   ──►  build/ios/AgereTokens*.swift    (iOS: SwiftUI Color + CGFloat)
 *                   ──►  build/android/*.xml             (Android: colors.xml + dimens.xml)
 *                   ──►  build/compose/AgereTokens*.kt   (Jetpack Compose)
 *
 * Run: npm run tokens   (also runs automatically before dev/build/test)
 */
import StyleDictionary from "style-dictionary";

/* ------------------------------------------------------------------ */
/* Helpers                                                             */
/* ------------------------------------------------------------------ */
function hexToRgb(hex) {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? h.split("").map((x) => x + x).join("") : h;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
}
/** "#111827" -> "221 39.3% 11%"  (HSL channels so Tailwind can apply <alpha-value>) */
function hexToHslChannels(hex) {
  const [r, g, b] = hexToRgb(hex).map((v) => v / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      default: h = (r - g) / d + 4;
    }
    h *= 60;
  }
  const f = (n) => Number(n.toFixed(1));
  return `${f(h)} ${f(s * 100)}% ${f(l * 100)}%`;
}
const px = (v) => (typeof v === "string" && v.endsWith("px") ? parseFloat(v) : null);
/** Filters run after transforms, so test the authored value. */
const authored = (t) => t.original?.$value ?? t.$value;
const isPx = (t) => t.$type === "dimension" && (px(t.$value) !== null || px(authored(t)) !== null);

/* ------------------------------------------------------------------ */
/* Custom transforms                                                   */
/* ------------------------------------------------------------------ */
StyleDictionary.registerTransform({
  name: "agere/color/hsl-channels",
  type: "value",
  filter: (t) => t.$type === "color",
  transform: (t) => (typeof t.$value === "string" && t.$value.startsWith("#") ? hexToHslChannels(t.$value) : t.$value),
});
StyleDictionary.registerTransform({
  name: "agere/size/px-number",
  type: "value",
  filter: isPx,
  transform: (t) => px(t.$value) ?? t.$value,
});
StyleDictionary.registerTransform({
  name: "agere/size/compose-dp",
  type: "value",
  filter: isPx,
  transform: (t) => (px(t.$value) !== null ? `${px(t.$value)}.dp` : t.$value),
});
StyleDictionary.registerTransform({
  name: "agere/size/android-dp",
  type: "value",
  filter: isPx,
  transform: (t) => (px(t.$value) !== null ? `${px(t.$value)}dp` : t.$value),
});

/* ------------------------------------------------------------------ */
/* Custom formats                                                      */
/* ------------------------------------------------------------------ */
const HEADER = "/**\n * Do not edit directly — generated by scripts/build-tokens.mjs from /tokens.\n */\n";

StyleDictionary.registerFormat({
  name: "agere/ts-nested",
  format: ({ dictionary, options }) => {
    const obj = {};
    for (const t of dictionary.allTokens) {
      let cur = obj;
      t.path.forEach((p, i) => {
        if (i === t.path.length - 1) cur[p] = t.$value;
        else cur = cur[p] ??= {};
      });
    }
    return `${HEADER}export const ${options.exportName} = ${JSON.stringify(obj, null, 2)} as const;\n`;
  },
});

/** Semantic-only filter: drop primitive colors from the CSS surface so components cannot reach them. */
const notPrimitiveColor = (t) => !(t.$type === "color" && t.filePath.includes("/primitive/"));
const onlyFile = (frag) => (t) => t.filePath.includes(frag);
const nativeSafe = (t) => t.$type === "color" || isPx(t) || t.$type === "number";

const cssTransforms = [
  "attribute/cti", "name/kebab", "agere/color/hsl-channels",
  "fontFamily/css", "cubicBezier/css", "shadow/css/shorthand",
];

/* ------------------------------------------------------------------ */
/* Builds                                                              */
/* ------------------------------------------------------------------ */
const base = ["tokens/primitive/**/*.json", "tokens/semantic/typography.json", "tokens/semantic/density.json", "tokens/component/**/*.json"];

async function build(theme) {
  const isLight = theme === "light";
  const sd = new StyleDictionary({
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "disabled" },
    source: [...base, `tokens/semantic/color.${theme}.json`],
    expand: { include: ["typography"] },
    platforms: {
      css: {
        prefix: "ag",
        transforms: cssTransforms,
        buildPath: "src/styles/",
        files: [
          {
            destination: `tokens.${theme}.css`,
            format: "css/variables",
            filter: isLight ? notPrimitiveColor : onlyFile(`color.${theme}.json`),
            options: {
              selector: isLight ? ":root, :host, [data-theme=\"light\"]" : ".dark, [data-theme=\"dark\"]",
              outputReferences: false,
              fileHeader: "agere",
            },
          },
        ],
      },
      ts: {
        transforms: ["attribute/cti", "name/camel", "fontFamily/css", "cubicBezier/css", "shadow/css/shorthand"],
        buildPath: "src/tokens/generated/",
        files: [
          {
            destination: `${theme}.ts`,
            format: "agere/ts-nested",
            filter: isLight ? () => true : onlyFile(`color.${theme}.json`),
            options: { exportName: isLight ? "lightTokens" : "darkTokens" },
          },
        ],
      },
      json: {
        transforms: ["attribute/cti", "name/kebab", "fontFamily/css", "cubicBezier/css", "shadow/css/shorthand"],
        buildPath: "build/tokens/",
        files: [{ destination: `tokens.${theme}.json`, format: "json/nested" }],
      },
      ios: {
        transforms: ["attribute/cti", "name/camel", "color/ColorSwiftUI", "agere/size/px-number"],
        buildPath: "build/ios/",
        files: [
          {
            destination: `AgereTokens${isLight ? "" : "Dark"}.swift`,
            format: "ios-swift/enum.swift",
            filter: (t) => nativeSafe(t) && (isLight ? notPrimitiveColor(t) : onlyFile(`color.${theme}.json`)(t)),
            options: { className: isLight ? "AgereTokens" : "AgereTokensDark", import: ["SwiftUI"] },
          },
        ],
      },
      android: {
        transforms: ["attribute/cti", "name/snake", "color/hex8android", "agere/size/android-dp"],
        buildPath: "build/android/",
        files: [
          { destination: isLight ? "values/agere_colors.xml" : "values-night/agere_colors.xml", format: "android/colors", filter: (t) => t.$type === "color" && (isLight ? notPrimitiveColor(t) : true) },
          ...(isLight ? [{ destination: "values/agere_dimens.xml", format: "android/dimens", filter: isPx }] : []),
        ],
      },
      compose: {
        transforms: ["attribute/cti", "name/camel", "color/composeColor", "agere/size/compose-dp"],
        buildPath: "build/compose/",
        files: [
          {
            destination: `AgereTokens${isLight ? "" : "Dark"}.kt`,
            format: "compose/object",
            filter: (t) => (t.$type === "color" || isPx(t)) && (isLight ? notPrimitiveColor(t) : onlyFile(`color.${theme}.json`)(t)),
            options: { className: isLight ? "AgereTokens" : "AgereTokensDark", packageName: "com.agere.ds.tokens" },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}

StyleDictionary.registerFileHeader({
  name: "agere",
  fileHeader: () => ["Do not edit directly — generated by scripts/build-tokens.mjs from /tokens."],
});

await build("light");
await build("dark");
console.log("✓ Agere tokens built (css · ts · json · ios · android · compose)");
