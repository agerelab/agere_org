/**
 * Syncs the Agere logo masters into the React <Logo> component.
 *
 * Source of truth: assets/brand/svg/*.svg — pure-vector masters from the brand team
 * (filled paths only, 1X = 100 SVG units; construction rules in assets/brand/README.md).
 * This script does NOT draw the logo; it only extracts viewBox + path data so the
 * component renders pixel-identical to the masters and can recolor them per theme.
 *
 *   assets/brand/svg/*.svg  →  src/brand/logo-paths.ts
 *   assets/brand/favicon/* → public/ (+ inlined into index.html)
 *
 * Run after replacing any master: npm run brand
 */
import fs from "node:fs";

const SRC = "assets/brand/svg";

function read(file) {
  const svg = fs.readFileSync(`${SRC}/${file}`, "utf8");
  const [, , w, h] = svg.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].map(([, attrs]) => {
    const d = attrs.match(/\sd="([^"]+)"/)[1];
    const transform = attrs.match(/transform="([^"]+)"/)?.[1];
    return transform ? { d, transform } : { d };
  });
  const rect = svg.match(/<rect\b[^>]*rx="([^"]+)"/);
  return { width: w, height: h, paths, ...(rect ? { tileRadius: Number(rect[1]) } : {}) };
}

const LOGO = {
  symbol: read("agere-symbol.svg"),
  symbolSmall: read("agere-symbol-small.svg"),
  wordmark: read("agere-wordmark.svg"),
  primary: read("agere-primary.svg"),
  primarySmall: read("agere-primary-small.svg"),
  stacked: read("agere-stacked.svg"),
  appIcon: read("agere-app-icon.svg"),
};

for (const [k, v] of Object.entries(LOGO)) {
  if (!v.paths.length) throw new Error(`No <path> found for ${k}`);
}

const ts = `/** Generated by scripts/build-brand.mjs from assets/brand/svg/*.svg — do not edit by hand. */
export interface LogoGeometry {
  width: number;
  height: number;
  paths: ReadonlyArray<{ d: string; transform?: string }>;
  tileRadius?: number;
}

export const LOGO = ${JSON.stringify(LOGO, null, 2)} as const satisfies Record<string, LogoGeometry>;
`;
fs.writeFileSync("src/brand/logo-paths.ts", ts);
fs.copyFileSync("assets/brand/favicon/favicon.svg", "public/favicon.svg");
for (const f of ["favicon.ico", "apple-touch-icon.png"]) fs.copyFileSync(`assets/brand/favicon/${f}`, `public/${f}`);

/* index.html inlines the SVG favicon as a data URI so the single-file docs build keeps it. */
const b64 = fs.readFileSync("assets/brand/favicon/favicon.svg").toString("base64");
const html = fs.readFileSync("index.html", "utf8");
fs.writeFileSync(
  "index.html",
  html.replace(/<link rel="icon" type="image\/svg\+xml" href="[^"]*"\s*\/?>/, `<link rel="icon" type="image/svg+xml" href="data:image/svg+xml;base64,${b64}" />`)
);
console.log(
  "brand: logo-paths.ts written —",
  Object.entries(LOGO).map(([k, v]) => `${k} ${v.width}×${v.height}`).join(" · ")
);
